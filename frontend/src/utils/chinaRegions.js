// 获取所有省份
export function getProvinces() {
  return Object.keys(chinaRegions);
}

// 获取指定省份的所有城市
export function getCities(province) {
  return province && chinaRegions[province] ? Object.keys(chinaRegions[province]) : [];
}

// 获取指定省份和城市的所有区县
export function getDistricts(province, city) {
  return province && city && chinaRegions[province] && chinaRegions[province][city] 
    ? chinaRegions[province][city] 
    : [];
}

